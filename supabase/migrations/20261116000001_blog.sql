-- DVINE H2O · blog
--
-- Articles written in Admin › Blog and shown at /blog. A post is either written here (`body`, a small
-- Markdown subset rendered without any raw HTML) or a link to a piece published elsewhere (`external_url`).
-- `product` + `category` decide where a post is offered on the product pages:
--   category 'value'  → the "Why this price?" link under that product's price
--   any category      → the "Worth reading" rows on that product's page
-- ════════════════════════════════════════════════════════════════════════════
create table if not exists dvine.posts (
  id              integer generated by default as identity primary key,
  slug            text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(slug) <= 90),
  title           text not null check (length(title) between 3 and 160),
  excerpt         text not null default '' check (length(excerpt) <= 400),
  category        text not null default 'hydration' check (category in ('benefits', 'value', 'case-study', 'hydration', 'guide', 'news')),
  product         text check (product in ('crystal', 'hyper', 'titan')),
  cover_image     text,
  cover_alt       text,
  body            text not null default '' check (length(body) <= 60000),
  external_url    text check (external_url is null or external_url ~ '^https://'),
  source          text,
  author          text not null default 'DVINE H2O editorial team',
  seo_description text,
  featured        boolean not null default false,
  status          text not null default 'draft' check (status in ('draft', 'published')),
  published_at    timestamptz,
  created_by      integer references dvine.staff (id),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists posts_status_published_idx on dvine.posts (status, published_at desc);
create index if not exists posts_product_idx on dvine.posts (product) where product is not null;

drop trigger if exists posts_touch on dvine.posts;
create trigger posts_touch before update on dvine.posts
  for each row execute function dvine.touch_updated_at();

-- Same locks as every other table: no API roles, RLS on, only the website's role has policies.
do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated', 'service_role'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on dvine.posts from %I', r);
    end if;
  end loop;
end $$;
revoke all on dvine.posts from public;

grant select, insert, update, delete on dvine.posts to dvine_app;
grant usage, select on all sequences in schema dvine to dvine_app;

alter table dvine.posts enable row level security;
drop policy if exists app_read on dvine.posts;
drop policy if exists app_insert on dvine.posts;
drop policy if exists app_update on dvine.posts;
drop policy if exists app_delete on dvine.posts;
create policy app_read on dvine.posts for select to dvine_app using (true);
create policy app_insert on dvine.posts for insert to dvine_app with check (true);
create policy app_update on dvine.posts for update to dvine_app using (true) with check (true);
create policy app_delete on dvine.posts for delete to dvine_app using (true);
