declare t text;
begin
  foreach t in array array['customers', 'products', 'cart_items', 'orders', 'payments', 'shipments', 'returns',
                           'referrals', 'enquiries', 'water_tests', 'service_tickets']
  loop
    execute format('create trigger %I before update on dvine.%I for each row execute function dvine.touch_updated_at()',
                   t || '_touch_updated_at', t);
  end loop;
end $$;
