-- ════════════════════════════════════════════════════════════════════════════
-- DVINE H2O · transaction database (Supabase Postgres)
--
-- Everything lives in the private schema `dvine`. It is NOT in the Data API's
-- exposed schemas, so the browser (anon / authenticated keys) cannot reach a
-- single row: the website reads and writes only through the server, connected
-- as the least-privilege role `dvine_app` (see 20261115000002_security.sql).
--
-- Money is stored as integer paise (bigint). Rates are basis points (1800 = 18%).
-- Timestamps are timestamptz (stored UTC, shown in IST by the app).
-- ════════════════════════════════════════════════════════════════════════════

create schema if not exists dvine;

-- updated_at bookkeeping for every table that has the column
create or replace function dvine.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

/* ───────────── Staff (admin dashboard users → Supabase Auth) ───────────── */
create table dvine.staff (
  id            integer generated by default as identity primary key,
  auth_user_id  uuid unique references auth.users (id) on delete set null,
  name          text not null check (length(name) between 1 and 120),
  email         text not null unique check (email = lower(email)),
